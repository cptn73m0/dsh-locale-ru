import fs from 'node:fs';
import path from 'node:path';

/**
 * Rebuild lib/client.js from locale/ru.json.
 *
 * Usage: node tools/build-client.mjs
 */
const root = path.resolve(import.meta.dirname, '..');
const dictionaryPath = path.join(root, 'locale', 'ru.json');
const outPath = path.join(root, 'lib', 'client.js');

const dictionaries = JSON.parse(fs.readFileSync(dictionaryPath, 'utf8'));
const namespaces = Object.keys(dictionaries);
let keys = 0;
for (const dict of Object.values(dictionaries)) keys += Object.keys(dict).length;

const banner = `/*
 * Russian language pack for DeepSeek Harness.
 * Generated by tools/build-client.mjs from locale/ru.json.
 */
`;

const body = `${banner}window.__ModuleLoader__.load({
\tid: "dsh-locale-ru",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

\t\t/** Switch the UI to Russian when the pack loads. */
\t\tconst AUTO_SELECT = true;
\t\tconst LABEL = "Русский";
\t\tconst DICTIONARIES = ${JSON.stringify(dictionaries, null, '\t\t')};

\t\tconst inject = ["locale"];

\t\tfunction apply(ctx) {
\t\t\tctx.effect(
\t\t\t\t() => ctx.locale.addLanguage({ id: "ru", label: LABEL, fallback: "en" }),
\t\t\t\t"ru-locale: language",
\t\t\t);
\t\t\tfor (const [namespace, dictionary] of Object.entries(DICTIONARIES)) {
\t\t\t\tctx.effect(
\t\t\t\t\t() => ctx.locale.register(namespace, "ru", dictionary),
\t\t\t\t\t"ru-locale: " + namespace,
\t\t\t\t);
\t\t\t}
\t\t\tif (AUTO_SELECT) {
\t\t\t\tctx.effect(() => {
\t\t\t\t\ttry {
\t\t\t\t\t\tif (ctx.locale.getSnapshot().active !== "ru") ctx.locale.setLocale("ru");
\t\t\t\t\t} catch (error) { console.error("ru-locale: setLocale failed", error); }
\t\t\t\t}, "ru-locale: activate");
\t\t\t}
\t\t}

\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t},
});
`;

fs.writeFileSync(outPath, body, 'utf8');
console.log(`wrote ${outPath} (${Buffer.byteLength(body)} bytes)`);
console.log(`${namespaces.length} namespaces, ${keys} keys`);
